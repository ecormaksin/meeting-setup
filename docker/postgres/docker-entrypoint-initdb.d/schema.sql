-- スキーマとオブジェクトをリセット
DROP SCHEMA IF EXISTS 主催者 CASCADE;
CREATE SCHEMA 主催者;

DROP SCHEMA IF EXISTS ミーティング CASCADE;
CREATE SCHEMA ミーティング;

DROP SCHEMA IF EXISTS 日程候補 CASCADE;
CREATE SCHEMA 日程候補;

DROP SCHEMA IF EXISTS 参加者 CASCADE;
CREATE SCHEMA 参加者;

DROP SCHEMA IF EXISTS 出欠 CASCADE;
CREATE SCHEMA 出欠;

DROP TYPE IF EXISTS 出欠.都合種別 CASCADE;
CREATE TYPE 出欠.都合種別 AS ENUM ('○', '△', '×');

-- 主催者 スキーマ
CREATE TABLE 主催者.主催者
(
  主催者番号 CHAR(26) PRIMARY KEY,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ミーティング スキーマ
CREATE TABLE ミーティング._ミーティング
(
  ミーティング番号 CHAR(26) PRIMARY KEY,
  件名 VARCHAR(30) NOT NULL,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ミーティング._ミーティングメモ
(
  ミーティング番号 CHAR(26) PRIMARY KEY REFERENCES ミーティング._ミーティング,
  メモ VARCHAR(100) NOT NULL,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 日程候補 スキーマ
CREATE SEQUENCE 日程候補.日程番号;

CREATE TABLE 日程候補._日程
(
  日程番号 INTEGER PRIMARY KEY,
  ミーティング番号 CHAR(26) NOT NULL REFERENCES ミーティング._ミーティング,
  開催日 DATE NOT NULL,
  開始時間 INTEGER NOT NULL CHECK(開始時間 >= 9 AND 開始時間 <= 17),
  開始分 INTEGER NOT NULL CHECK(開始分 = 0 OR 開始分 = 30),
  会議時間 INTEGER NOT NULL CHECK(会議時間 >= 30 AND 会議時間 <= 120 AND MOD(会議時間, 30) = 0),
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (ミーティング番号, 開催日, 開始時間, 開始分, 会議時間)
);

-- 参加者 スキーマ
CREATE TABLE 参加者.参加者
(
  参加者番号 CHAR(26) PRIMARY KEY,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE 参加者._最新の参加者名
(
  参加者番号 CHAR(26) PRIMARY KEY REFERENCES 参加者.参加者,
  参加者名 VARCHAR(10) NOT NULL,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- 出欠 スキーマ
CREATE TABLE 出欠._出欠
(
  出欠番号 CHAR(26) PRIMARY KEY,
  ミーティング番号 CHAR(26) NOT NULL REFERENCES ミーティング._ミーティング,
  参加者番号 CHAR(26) NOT NULL REFERENCES 参加者.参加者,
  参加者名 VARCHAR(10) NOT NULL,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (ミーティング番号, 参加者番号),
  UNIQUE (ミーティング番号, 参加者名)
);

CREATE SEQUENCE 出欠.都合番号;

CREATE TABLE 出欠._都合
(
  都合番号 INTEGER PRIMARY KEY,
  出欠番号 CHAR(26) NOT NULL REFERENCES 出欠._出欠,
  日程番号 INTEGER NOT NULL REFERENCES 日程候補._日程,
  都合種別 出欠.都合種別 NOT NULL,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (出欠番号, 日程番号)
);

CREATE TABLE 出欠._出欠コメント
(
  出欠番号 CHAR(26) PRIMARY KEY REFERENCES 出欠._出欠,
  出欠コメント VARCHAR(100) NOT NULL,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ミーティングと主催者の関連テーブル
CREATE TABLE 主催者._ミーティングと主催者
(
  ミーティング番号 CHAR(26) PRIMARY KEY REFERENCES ミーティング._ミーティング,
  主催者番号 CHAR(26) NOT NULL REFERENCES 主催者.主催者,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
