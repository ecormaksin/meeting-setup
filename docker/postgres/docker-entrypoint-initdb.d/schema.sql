-- スキーマとオブジェクトをリセット
DROP SCHEMA IF EXISTS ミーティング CASCADE;
CREATE SCHEMA ミーティング;

DROP SCHEMA IF EXISTS 日程候補 CASCADE;
CREATE SCHEMA 日程候補;

DROP SCHEMA IF EXISTS 出欠 CASCADE;
CREATE SCHEMA 出欠;

-- ミーティング スキーマ
CREATE TABLE ミーティング.ミーティング
(
  ミーティング番号 CHAR(26) PRIMARY KEY,
  件名 VARCHAR(30) NOT NULL,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ミーティング.主催者端末
(
  ミーティング番号 CHAR(26) PRIMARY KEY REFERENCES ミーティング.ミーティング,
  IPアドレス VARCHAR(40) NOT NULL,
  OSファミリー VARCHAR(10) NOT NULL,
  ユーザーエージェントファミリー VARCHAR(30) NOT NULL,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ミーティング.ミーティングメモ
(
  ミーティング番号 CHAR(26) PRIMARY KEY REFERENCES ミーティング.ミーティング,
  メモ TEXT NOT NULL,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 日程候補 スキーマ
CREATE SEQUENCE 日程候補.日程候補番号;

CREATE TABLE 日程候補.日程候補
(
  日程候補番号 INTEGER PRIMARY KEY,
  ミーティング番号 CHAR(26) NOT NULL REFERENCES ミーティング.ミーティング,
  開始日時 TIMESTAMP NOT NULL,
  終了日時 TIMESTAMP NOT NULL,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (ミーティング番号, 開始日時, 終了日時)
);

-- 出欠 スキーマ
CREATE TABLE 出欠.出欠
(
  出欠ID CHAR(32) PRIMARY KEY,
  ミーティング番号 CHAR(26) NOT NULL REFERENCES ミーティング.ミーティング,
  参加者名 VARCHAR(40) NOT NULL,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (ミーティング番号, 参加者名)
);

CREATE SEQUENCE 出欠.都合番号;

CREATE TABLE 出欠.都合
(
  都合番号 INTEGER PRIMARY KEY,
  出欠ID CHAR(32) NOT NULL REFERENCES 出欠.出欠,
  日程候補番号 INTEGER NOT NULL REFERENCES 日程候補.日程候補,
  都合種別 VARCHAR(16) NOT NULL,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (出欠ID, 日程候補番号)
);

CREATE TABLE 出欠.出欠コメント
(
  出欠ID CHAR(32) PRIMARY KEY REFERENCES 出欠.出欠,
  出欠コメント VARCHAR(255) NOT NULL,
  登録日時 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
